'use strict';
// Vercel build step, after `vite build` (npm run vercel-build). Vercel runs src/app.js as one function and its CDN
// only carries files committed to public/ (dni-tracker.js), not files a build writes there. The web app therefore
// ships inside the function, as generated modules required by src/app.js so they are always in its bundle:
//   web/dist/index.html → src/generated/index-html.js
//   web/dist/assets/*   → src/generated/web-assets.js  (base64, so Vercel's ESM→CommonJS pass cannot rewrite them)
//   migrations/schema.sql → src/generated/schema-sql.js
// Nothing here runs for a local or Docker build.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dist = path.join(root, 'web', 'dist');
const gen = path.join(root, 'src', 'generated');

if (!fs.existsSync(path.join(dist, 'index.html'))) { console.error('web/dist is missing: run vite build first'); process.exit(1); }

const TYPES = { '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.woff2': 'font/woff2', '.svg': 'image/svg+xml', '.png': 'image/png' };
const assets = {};
for (const name of fs.readdirSync(path.join(dist, 'assets'))) {
  assets[name] = { type: TYPES[path.extname(name)] || 'application/octet-stream', base64: fs.readFileSync(path.join(dist, 'assets', name)).toString('base64') };
}

fs.mkdirSync(gen, { recursive: true });
const asModule = (value) => `'use strict';\n// Generated by tools/vercel-prepare.js. Do not edit.\nmodule.exports = ${JSON.stringify(value)};\n`;
fs.writeFileSync(path.join(gen, 'index-html.js'), asModule(fs.readFileSync(path.join(dist, 'index.html'), 'utf8')));
fs.writeFileSync(path.join(gen, 'web-assets.js'), asModule(assets));
fs.writeFileSync(path.join(gen, 'schema-sql.js'), asModule(fs.readFileSync(path.join(root, 'migrations', 'schema.sql'), 'utf8')));
console.log(`vercel-prepare: src/generated/ ready (${Object.keys(assets).length} assets)`);

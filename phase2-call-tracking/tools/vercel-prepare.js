'use strict';
// Vercel build step, after `vite build` (npm run vercel-build). Vercel serves public/** from its CDN and runs
// src/app.js as one function, so:
//   web/dist/*            → public/            the web app (index.html, assets/)
//   public/dni-tracker.js → public/static/     the website snippet keeps its /static/dni-tracker.js address
//   index.html, schema    → src/generated/*.js  required by the function, so they are always in its bundle
// Nothing here runs for a local or Docker build.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dist = path.join(root, 'web', 'dist');
const pub = path.join(root, 'public');
const gen = path.join(root, 'src', 'generated');

if (!fs.existsSync(path.join(dist, 'index.html'))) { console.error('web/dist is missing: run vite build first'); process.exit(1); }
fs.cpSync(dist, pub, { recursive: true });
fs.mkdirSync(path.join(pub, 'static'), { recursive: true });
fs.copyFileSync(path.join(pub, 'dni-tracker.js'), path.join(pub, 'static', 'dni-tracker.js'));

fs.mkdirSync(gen, { recursive: true });
const asModule = (text) => `'use strict';\n// Generated by tools/vercel-prepare.js. Do not edit.\nmodule.exports = ${JSON.stringify(text)};\n`;
fs.writeFileSync(path.join(gen, 'index-html.js'), asModule(fs.readFileSync(path.join(dist, 'index.html'), 'utf8')));
fs.writeFileSync(path.join(gen, 'schema-sql.js'), asModule(fs.readFileSync(path.join(root, 'migrations', 'schema.sql'), 'utf8')));
console.log('vercel-prepare: public/ and src/generated/ ready');
